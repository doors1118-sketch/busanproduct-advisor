# 2. 조항 참조(예: "지방계약법 시행령 제25조")에서 약칭 추출
# ──────────────────────────────────────────────────────────
# "지방계약법 시행령 제25조" → 약칭="지방계약법 시행령", 조항="제25조"
# "국가계약법 시행령 제26조 제1항" → 약칭="국가계약법 시행령", 조항="제26조 제1항"

import re

_ARTICLE_PATTERN = re.compile(
    r"^(.+?)\s*(제\d+조(?:의\d+)?(?:\s*제\d+항)?(?:\s*제\d+호)?)(.*)$"
)


def parse_law_reference(term: str) -> tuple[str | None, str | None]:
    """
    법령 참조 문자열에서 (약칭, 조항) 분리.
    예: "지방계약법 시행령 제25조" → ("지방계약법 시행령", "제25조")
    예: "소액수의계약" → (None, None)  (조항 참조가 아님)
    """
    m = _ARTICLE_PATTERN.match(term.strip())
    if m:
        alias = m.group(1).strip()
        article = m.group(2).strip()
        return alias, article
    return None, None


def resolve_alias(term: str) -> str | None:
    """
    약칭 또는 조항 참조를 정식 source_name으로 변환.
    직접 매칭되면 바로 반환, 조항 참조면 약칭 부분만 변환.
    """
    # 1) 직접 매칭
    if term in LAW_ALIAS_MAP:
        return LAW_ALIAS_MAP[term]

    # 2) 조항 참조 ("지방계약법 시행령 제25조")
    alias, _ = parse_law_reference(term)
    if alias and alias in LAW_ALIAS_MAP:
        return LAW_ALIAS_MAP[alias]

    return None
